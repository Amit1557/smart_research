/**
 * SmartDoc RAG - Client Application Logic
 */

document.addEventListener("DOMContentLoaded", () => {
    // ── Elements ────────────────────────────────────────────────────────────
    const docTitleInput = document.getElementById("doc-title");
    const docTextInput = document.getElementById("doc-text");
    const btnIndex = document.getElementById("btn-index");
    const btnReset = document.getElementById("btn-reset");

    const ingestStats = document.getElementById("ingest-stats");
    const statChunks = document.getElementById("stat-chunks");
    const statDim = document.getElementById("stat-dim");
    const statTime = document.getElementById("stat-time");

    const queryForm = document.getElementById("query-form");
    const queryInput = document.getElementById("query-input");
    const btnAsk = document.getElementById("btn-ask");

    const loadingSpinner = document.getElementById("loading-spinner");
    const emptyState = document.getElementById("empty-state");
    const resultsContainer = document.getElementById("results-container");

    const answerContent = document.getElementById("answer-content");
    const metricScore = document.getElementById("metric-score");
    const metricLatency = document.getElementById("metric-latency");
    const sourcesList = document.getElementById("sources-list");

    // Sample Preset Buttons
    const btnSamplePolicy = document.getElementById("btn-sample-policy");
    const btnSampleResearch = document.getElementById("btn-sample-research");
    const btnSampleWarranty = document.getElementById("btn-sample-warranty");

    // ── Sample Presets Data ─────────────────────────────────────────────────
    const SAMPLES = {
        policy: {
            title: "NexusTech Employee Handbook 2026",
            text: `NexusTech Enterprise Human Resources Policy & Perks Guide (2026 Edition)

1. Annual Leave & Work From Home (WFH):
All full-time employees receive 25 paid annual leaves (vacation days) per calendar year. In addition, employees are entitled to 10 sick leaves and 12 public holidays. NexusTech operates on a hybrid-first model: team members may work remotely up to 3 days per week with manager coordination. Core collaboration hours are 10:00 AM to 4:00 PM local time.

2. Comprehensive Health & Wellness Benefits:
NexusTech provides 100% employer-sponsored health, dental, and vision insurance for employees and 80% coverage for eligible dependents. Every employee receives an annual $1,200 Wellness & Mental Health stipend, which can be applied toward gym memberships, ergonomic home equipment, or licensed therapy sessions.

3. Professional Learning & Upskilling Stipend:
Each team member has access to an annual $2,000 professional education budget for approved technical certifications (e.g. AWS, GCP, PyTorch), books, and conferences. Courses must align with the employee's career progression plan.

4. Notice Period & Resignation Protocol:
Employees in individual contributor roles must provide a minimum of 30 days written notice before their final working day. Engineering leads, managers, and executives are subject to a 60-day notice period to ensure seamless knowledge transfer and project handover. During the notice period, all company hardware and access tokens must be surrendered to IT.`
        },
        research: {
            title: "Transformer Attention Mechanisms & Vector Space Abstract",
            text: `Paper Title: High-Dimensional Semantic Geometry in Transformer Language Models

Abstract:
Modern transformer-based neural architectures leverage multi-head self-attention mechanisms to map discrete linguistic tokens into continuous vector manifolds. In this study, we evaluate the performance of dense sentence embeddings generated by MiniLM architectures (384 dimensions) versus traditional sparse TF-IDF and BM25 bag-of-words heuristics.

Key Findings:
1. Cosine similarity computed over normalized 384-dimensional dense vectors consistently outperforms lexical matching on semantic paraphrase detection, achieving a 24.8% increase in Top-3 retrieval recall.
2. Embedding normalization bounds the dot product strictly within [-1.0, 1.0], enabling constant-time similarity indexing when utilizing inverted vector indexes like HNSW in Qdrant.
3. When retrieved vector chunks are provided as grounded context to a large language model (Gemini), factual hallucinations decrease by 87.4% compared to zero-shot generation across technical and legal question benchmarks.`
        },
        warranty: {
            title: "AeroSound Pro Headphone Warranty & Support",
            text: `AeroSound Pro Wireless ANC Headphones - Official Warranty & Return Guidelines

Warranty Duration & Coverage:
The AeroSound Pro comes with a 2-Year Limited Manufacturer Warranty covering defects in materials, Bluetooth hardware failure, and battery degradation exceeding 30% within 24 months of purchase date. Physical accidental damage, water submersion beyond IPX4 rating, and unauthorized third-party repairs are not covered.

Replacement & RMA Process:
To file an RMA claim, customers must submit proof of purchase and product serial number via support@aerosound.com. If verified, a prepaid return shipping label will be provided within 48 hours. Replacement units are dispatched within 3-5 business days upon receiving the defective unit.

30-Day Money-Back Guarantee:
Customers who purchase directly through the official website may return the product within 30 days for a full refund, provided all original packaging, cables, and ear-cushion accessories are intact.`
        }
    };

    // Load default sample on initial start
    docTitleInput.value = SAMPLES.policy.title;
    docTextInput.value = SAMPLES.policy.text;

    // Preset Click Handlers
    btnSamplePolicy.addEventListener("click", () => {
        docTitleInput.value = SAMPLES.policy.title;
        docTextInput.value = SAMPLES.policy.text;
    });

    btnSampleResearch.addEventListener("click", () => {
        docTitleInput.value = SAMPLES.research.title;
        docTextInput.value = SAMPLES.research.text;
    });

    btnSampleWarranty.addEventListener("click", () => {
        docTitleInput.value = SAMPLES.warranty.title;
        docTextInput.value = SAMPLES.warranty.text;
    });

    // ── Index Document (RAG Step 1 & 2) ─────────────────────────────────────
    btnIndex.addEventListener("click", async () => {
        const title = docTitleInput.value.trim() || "Untitled Document";
        const text = docTextInput.value.trim();

        if (!text) {
            alert("Please enter or paste document content to index.");
            return;
        }

        btnIndex.disabled = true;
        btnIndex.innerHTML = `<span class="pulsing-loader" style="width:14px;height:14px;margin:0;border-width:2px;display:inline-block;vertical-align:middle;"></span> Indexing...`;

        try {
            const res = await fetch("/api/index", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    document_title: title,
                    text: text,
                    chunk_size: 80
                })
            });

            if (!res.ok) {
                const err = await res.json();
                throw new Error(err.detail || "Indexing failed");
            }

            const data = await res.json();
            
            // Show stats card
            ingestStats.classList.remove("hidden");
            statChunks.textContent = data.chunks_indexed;
            statDim.textContent = `${data.embedding_dimensions}-D`;
            statTime.textContent = `${data.time_taken_ms} ms`;

        } catch (err) {
            alert(`Error: ${err.message}`);
        } finally {
            btnIndex.disabled = false;
            btnIndex.innerHTML = `<span class="btn-icon">⚡</span> Index & Embed Document`;
        }
    });

    // ── Reset Vector Database ───────────────────────────────────────────────
    btnReset.addEventListener("click", async () => {
        if (!confirm("Are you sure you want to reset the in-memory vector database?")) return;

        try {
            const res = await fetch("/api/reset", { method: "POST" });
            if (res.ok) {
                ingestStats.classList.add("hidden");
                resultsContainer.classList.add("hidden");
                emptyState.classList.remove("hidden");
                alert("Vector database reset successfully.");
            }
        } catch (err) {
            alert("Failed to reset database.");
        }
    });

    // ── Query RAG & Gen AI (Step 3 & 4) ─────────────────────────────────────
    queryForm.addEventListener("submit", async (e) => {
        e.preventDefault();
        const question = queryInput.value.trim();
        if (!question) return;

        // UI transitions
        emptyState.classList.add("hidden");
        resultsContainer.classList.add("hidden");
        loadingSpinner.classList.remove("hidden");
        btnAsk.disabled = true;

        try {
            const res = await fetch("/api/query", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    question: question,
                    top_k: 3
                })
            });

            if (!res.ok) {
                const err = await res.json();
                throw new Error(err.detail || "Query failed");
            }

            const data = await res.json();

            // Render Gen AI Answer (using marked.js if available)
            if (typeof marked !== "undefined" && marked.parse) {
                answerContent.innerHTML = marked.parse(data.answer);
            } else {
                answerContent.textContent = data.answer;
            }

            // Render ML Telemetry
            metricScore.textContent = `${data.ml_metrics.highest_similarity_score}%`;
            metricLatency.textContent = `${data.ml_metrics.latency_ms} ms`;

            // Render Retrieved Sources
            sourcesList.innerHTML = "";
            data.retrieved_sources.forEach(src => {
                const card = document.createElement("div");
                card.className = "source-card";
                card.innerHTML = `
                    <div class="source-header">
                        <span class="source-tag">Source ${src.rank} • Chunk #${src.chunk_id} (${src.document})</span>
                        <span class="source-score">Cosine Match: ${src.similarity_score}%</span>
                    </div>
                    <div class="source-snippet">"${src.text}"</div>
                `;
                sourcesList.appendChild(card);
            });

            // Reveal results
            resultsContainer.classList.remove("hidden");

        } catch (err) {
            alert(`Query Error: ${err.message}`);
            emptyState.classList.remove("hidden");
        } finally {
            loadingSpinner.classList.add("hidden");
            btnAsk.disabled = false;
        }
    });

    // ── Suggested Chips Click Handlers ──────────────────────────────────────
    document.querySelectorAll(".chip-btn").forEach(btn => {
        btn.addEventListener("click", () => {
            queryInput.value = btn.getAttribute("data-query");
            btnAsk.click();
        });
    });
});
